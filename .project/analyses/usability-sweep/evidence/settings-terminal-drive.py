import json, os, pathlib, subprocess, time
SOCKET=os.environ['QA_SOCKET']
OUT=pathlib.Path(__file__).resolve().parents[1] / 'captures'
OUT.mkdir(parents=True,exist_ok=True)
PREFIX=os.environ.get('QA_PREFIX','dark-fullscreen')
def tmux(*args):
    return subprocess.check_output(['tmux','-L',SOCKET,*args],text=True)
def screen(): return tmux('capture-pane','-p','-t','qa')
def key(*args):
    tmux('send-keys','-t','qa',*args)
    time.sleep(.22)
def text(value):
    tmux('send-keys','-t','qa','-l',value)
    time.sleep(.25)
def wait(value,timeout=6):
    deadline=time.monotonic()+timeout
    while time.monotonic()<deadline:
        s=screen()
        if value in s: return s
        time.sleep(.1)
    raise AssertionError('Missing '+repr(value)+'\n'+screen())
def capture(name):
    s=screen()
    (OUT/(PREFIX+'-'+name+'.txt')).write_text(s)
    (OUT/(PREFIX+'-'+name+'.ansi')).write_text(tmux('capture-pane','-e','-p','-t','qa'))
    return s
def choose(query):
    text(query)
    wait(query)
    key('Enter')
